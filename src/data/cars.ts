export function yearsOf(model: CarModel): number[] {
  const end = model.to ?? CURRENT_YEAR
  const years: number[] = []
  for (let year = end; year >= model.from; year -= 1) years.push(year)
  return years
}

export function findBrand(id: string) {
  return BRANDS.find((brandItem) => brandItem.id === id)
}
