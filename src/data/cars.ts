export type CarModel = {
  name: string
  from: number
  to?: number
}

export type CarBrand = {
  id: string
  name: string
  models: CarModel[]
}

type Row = [string, number, number?]

function brand(id: string, name: string, rows: Row[]): CarBrand {
  return {
    id,
    name,
    models: rows.map(([modelName, from, to]) =>
      to ? { name: modelName, from, to } : { name: modelName, from },
    ),
  }
}

